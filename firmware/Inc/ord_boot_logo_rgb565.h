/**
 * @brief Renders the RETRO DIAG boot splash frame with gradient shader
 * @param fb Pointer to 160x80 RGB565 framebuffer (25,600 bytes)
 * @param frame_tick Frame counter or animation phase for the gradient shader
 */
static inline void ord_boot_render_frame(uint16_t *fb, uint32_t frame_tick) {
    if (!fb) return;
    uint32_t byte_idx = 0U;
    for (uint16_t y = 0U; y < ORD_LCD_HEIGHT; y++) {
        uint16_t row_offset = (uint16_t)(y * ORD_LCD_WIDTH);
        for (uint16_t x_grp = 0U; x_grp < (ORD_LCD_WIDTH / 4U); x_grp++) {
            uint8_t b = k_ord_logo_mask_2bpp[byte_idx++];
            for (uint8_t p = 0U; p < 4U; p++) {
                uint16_t x = (uint16_t)(x_grp * 4U + p);
                uint8_t val = (uint8_t)((b >> (6U - p * 2U)) & 0x03U);
                uint16_t color;
                switch (val) {
                    case 0U: /* Background: Obsidian Dark Scanlines */
                        color = (y & 1U) ? 0x0862U : 0x0020U;
                        break;
                    case 1U: /* FDD Emblem & Flux Pulse: Dynamic Rainbow Gradient */
                        color = k_ord_gradient_lut[(x + (frame_tick * 2U)) & 0xFFU];
                        break;
                    case 2U: /* Bus Traces & Vias: Electric Cyan / Blue */
                        color = 0x0BEFU;
                        break;
                    case 3U: /* Typography & Subtitle: Crisp Luminescent White */
                    default:
                        color = 0xF79EU;
                        break;
                }
                fb[row_offset + x] = color;
            }
        }
    }
}

